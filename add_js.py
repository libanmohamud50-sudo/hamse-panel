with open('public/index.html', 'r', encoding='utf-8') as f:
    html = f.read()

if 'function loadServerFiles' in html:
    print("JS functions horey ayay u jireen")
else:
    js_lines = []
    js_lines.append("")
    js_lines.append("<script>")
    js_lines.append("// ===== WORKER EDITOR + SERVER EDIT =====")
    js_lines.append("function updateLineNumbers(taId, lnId) {")
    js_lines.append("  var ta = document.getElementById(taId);")
    js_lines.append("  var ln = document.getElementById(lnId);")
    js_lines.append("  if (!ta || !ln) return;")
    js_lines.append("  var lines = ta.value.split(String.fromCharCode(10)).length;")
    js_lines.append("  var s = '';")
    js_lines.append("  for (var i = 1; i <= lines; i++) s += i + String.fromCharCode(10);")
    js_lines.append("  ln.textContent = s;")
    js_lines.append("}")
    js_lines.append("function syncScroll(taId, lnId) {")
    js_lines.append("  var ta = document.getElementById(taId);")
    js_lines.append("  var ln = document.getElementById(lnId);")
    js_lines.append("  if (ta && ln) ln.scrollTop = ta.scrollTop;")
    js_lines.append("}")
    js_lines.append("function toggleLineNumbers(taId, lnId) {")
    js_lines.append("  var ln = document.getElementById(lnId);")
    js_lines.append("  if (ln) ln.style.display = ln.style.display === 'none' ? 'block' : 'none';")
    js_lines.append("}")
    js_lines.append("var CURRENT_FILE = '';")
    js_lines.append("async function loadServerFiles() {")
    js_lines.append("  try {")
    js_lines.append("    var data = await api('/api/admin/server/files');")
    js_lines.append("    var fl = document.getElementById('fileList');")
    js_lines.append("    if (!fl) return;")
    js_lines.append("    fl.innerHTML = data.files.map(function(f) {")
    js_lines.append("      var cls = f.missing ? 'missing' : '';")
    js_lines.append("      var label = f.name + (f.missing ? ' (ma jiro)' : '');")
    js_lines.append("      return '<button onclick=\"loadFile(\\'' + f.name + '\\')\" class=\"' + cls + '\">' + label + '</button>';")
    js_lines.append("    }).join('');")
    js_lines.append("  } catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("  loadWorkerCode();")
    js_lines.append("  loadEnv();")
    js_lines.append("}")
    js_lines.append("async function loadFile(name) {")
    js_lines.append("  try {")
    js_lines.append("    document.querySelectorAll('#fileList button').forEach(function(b) { b.classList.toggle('active', b.textContent.indexOf(name) === 0); });")
    js_lines.append("    var data = await api('/api/admin/server/file?name=' + encodeURIComponent(name));")
    js_lines.append("    document.getElementById('currentFile').value = data.name;")
    js_lines.append("    document.getElementById('codeEditor').value = data.content;")
    js_lines.append("    CURRENT_FILE = name;")
    js_lines.append("    updateLineNumbers('codeEditor', 'lineNumbers');")
    js_lines.append("    showToast('Fayl la furay: ' + name, 'success');")
    js_lines.append("  } catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("}")
    js_lines.append("function selectAllCode() { var ta = document.getElementById('codeEditor'); ta.focus(); ta.select(); showToast('Qoraalka la doortay', 'info'); }")
    js_lines.append("function removeAllCode() { if (!confirm('Tirtir qoraalka oo dhan?')) return; document.getElementById('codeEditor').value = ''; updateLineNumbers('codeEditor', 'lineNumbers'); showToast('La tirtiray', 'info'); }")
    js_lines.append("function copyCode() { var ta = document.getElementById('codeEditor'); ta.select(); document.execCommand('copy'); showToast('Copy la sameeyay', 'success'); }")
    js_lines.append("async function pasteCode() {")
    js_lines.append("  try { var t = await navigator.clipboard.readText(); document.getElementById('codeEditor').value = t; updateLineNumbers('codeEditor', 'lineNumbers'); showToast('Paste la sameeyay', 'success'); }")
    js_lines.append("  catch (e) { showToast('Paste ma shaqeyn', 'error'); }")
    js_lines.append("}")
    js_lines.append("async function saveFile() {")
    js_lines.append("  var name = document.getElementById('currentFile').value;")
    js_lines.append("  var content = document.getElementById('codeEditor').value;")
    js_lines.append("  if (!name) return showToast('Dooro fayl marka hore', 'error');")
    js_lines.append("  try { await api('/api/admin/server/file', 'POST', { name: name, content: content }); showToast('Fayl la keydiyay', 'success'); }")
    js_lines.append("  catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("}")
    js_lines.append("async function loadWorkerCode() {")
    js_lines.append("  try {")
    js_lines.append("    var data = await api('/api/admin/worker/code');")
    js_lines.append("    var we = document.getElementById('workerEditor');")
    js_lines.append("    if (we) { we.value = data.code; updateLineNumbers('workerEditor', 'workerLineNumbers'); }")
    js_lines.append("    var ws = document.getElementById('workerStatus');")
    js_lines.append("    if (ws) { ws.textContent = 'Loaded'; ws.className = 'badge badge-online'; }")
    js_lines.append("  } catch (e) {")
    js_lines.append("    var ws2 = document.getElementById('workerStatus');")
    js_lines.append("    if (ws2) { ws2.textContent = 'Error'; ws2.className = 'badge badge-offline'; }")
    js_lines.append("  }")
    js_lines.append("}")
    js_lines.append("function selectAllWorker() { var ta = document.getElementById('workerEditor'); ta.focus(); ta.select(); showToast('Worker code la doortay', 'info'); }")
    js_lines.append("function removeAllWorker() { if (!confirm('Tirtir worker code oo dhan?')) return; document.getElementById('workerEditor').value = ''; updateLineNumbers('workerEditor', 'workerLineNumbers'); showToast('La tirtiray', 'info'); }")
    js_lines.append("function copyWorker() { var ta = document.getElementById('workerEditor'); ta.select(); document.execCommand('copy'); showToast('Worker copy la sameeyay', 'success'); }")
    js_lines.append("async function pasteWorker() {")
    js_lines.append("  try { var t = await navigator.clipboard.readText(); document.getElementById('workerEditor').value = t; updateLineNumbers('workerEditor', 'workerLineNumbers'); showToast('Paste la sameeyay', 'success'); }")
    js_lines.append("  catch (e) { showToast('Paste ma shaqeyn', 'error'); }")
    js_lines.append("}")
    js_lines.append("function reloadWorker() { loadWorkerCode(); showToast('Dib loo soo dejiyay', 'info'); }")
    js_lines.append("async function saveWorkerCode() {")
    js_lines.append("  var code = document.getElementById('workerEditor').value;")
    js_lines.append("  try { await api('/api/admin/worker/code', 'POST', { code: code }); showToast('Worker code la keydiyay', 'success'); }")
    js_lines.append("  catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("}")
    js_lines.append("async function deployWorker() {")
    js_lines.append("  if (!confirm('Deploy Worker-ka Cloudflare?')) return;")
    js_lines.append("  try {")
    js_lines.append("    showToast('Deploy socda...', 'info');")
    js_lines.append("    await saveWorkerCode();")
    js_lines.append("    var data = await api('/api/admin/server/deploy', 'POST');")
    js_lines.append("    var r = data.result;")
    js_lines.append("    var msg = '';")
    js_lines.append("    if (r.worker && r.worker.ok) msg += 'Worker OK. ';")
    js_lines.append("    else if (r.worker) msg += 'Worker: ' + (r.worker.error || 'fail') + '. ';")
    js_lines.append("    if (r.railway && r.railway.ok) msg += 'Railway OK. ';")
    js_lines.append("    showToast(msg || 'Deploy dhammaad', 'success');")
    js_lines.append("    loadDeployLog();")
    js_lines.append("  } catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("}")
    js_lines.append("async function testWorker() {")
    js_lines.append("  try {")
    js_lines.append("    var url = document.getElementById('envWorkerUrl').value.trim();")
    js_lines.append("    if (!url) return showToast('Geli Worker URL', 'error');")
    js_lines.append("    var r = await fetch(url + '/api/health');")
    js_lines.append("    var j = await r.json();")
    js_lines.append("    showToast('Worker: ' + JSON.stringify(j).substring(0, 80), 'success');")
    js_lines.append("  } catch (e) { showToast('Worker test fail', 'error'); }")
    js_lines.append("}")
    js_lines.append("async function loadEnv() {")
    js_lines.append("  try {")
    js_lines.append("    var data = await api('/api/admin/env');")
    js_lines.append("    var map = { panel_token: 'envPanelToken', worker_url: 'envWorkerUrl', cf_account_id: 'envCfAccount', cf_api_token: 'envCfToken', cf_worker_name: 'envCfWorkerName', railway_webhook: 'envRailwayWebhook' };")
    js_lines.append("    for (var k in map) { if (data.env[k]) { var el = document.getElementById(map[k]); if (el) el.value = data.env[k]; } }")
    js_lines.append("  } catch (e) {}")
    js_lines.append("}")
    js_lines.append("async function saveAllEnv() {")
    js_lines.append("  var fields = [['panel_token','envPanelToken'],['worker_url','envWorkerUrl'],['cf_account_id','envCfAccount'],['cf_api_token','envCfToken'],['cf_worker_name','envCfWorkerName'],['railway_webhook','envRailwayWebhook']];")
    js_lines.append("  try {")
    js_lines.append("    for (var i = 0; i < fields.length; i++) {")
    js_lines.append("      var val = document.getElementById(fields[i][1]).value.trim();")
    js_lines.append("      if (val) await api('/api/admin/env', 'POST', { key: fields[i][0], value: val });")
    js_lines.append("    }")
    js_lines.append("    showToast('Env la keydiyay', 'success');")
    js_lines.append("  } catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("}")
    js_lines.append("async function deployAll() {")
    js_lines.append("  if (!confirm('Deploy bilaabo?')) return;")
    js_lines.append("  try {")
    js_lines.append("    var data = await api('/api/admin/server/deploy', 'POST');")
    js_lines.append("    showToast('Deploy dhammaad', 'success');")
    js_lines.append("    loadDeployLog();")
    js_lines.append("  } catch (e) { showToast(e.message, 'error'); }")
    js_lines.append("}")
    js_lines.append("async function loadDeployLog() {")
    js_lines.append("  try {")
    js_lines.append("    var data = await api('/api/admin/server/deploy-log');")
    js_lines.append("    var box = document.getElementById('deployLogCard');")
    js_lines.append("    var content = document.getElementById('deployLogContent');")
    js_lines.append("    if (!box || !content) return;")
    js_lines.append("    box.style.display = 'block';")
    js_lines.append("    content.innerHTML = data.logs.map(function(l) { return '<div style=\"padding:6px;border-bottom:1px solid #e5eaf1;\"><b>[' + l.created_at + ']</b> ' + l.action + ' ' + l.status + '<div style=\"color:#6b7c93;font-size:11px;\">' + (l.message || '') + '</div></div>'; }).join('') || 'Ma jiro log';")
    js_lines.append("  } catch (e) {}")
    js_lines.append("}")
    js_lines.append("(function() {")
    js_lines.append("  var orig = window.showSection;")
    js_lines.append("  window.showSection = function(name) {")
    js_lines.append("    if (orig) orig(name);")
    js_lines.append("    if (name === 'server') loadServerFiles();")
    js_lines.append("  };")
    js_lines.append("})();")
    js_lines.append("</script>")
    js_lines.append("</body>")

    js_new = "\n".join(js_lines)

    if '</body>' in html:
        html = html.replace('</body>', js_new)
        print("OK: JS functions la daray")
    else:
        html = html + js_new
        print("OK: JS functions la daray (append)")

with open('public/index.html', 'w', encoding='utf-8') as f:
    f.write(html)

